"""Bleep the swearing in the bloopers, and write a censored caption text alongside.

Two halves have to agree or the censoring is pointless: the audio is muted and replaced with
a tone, and the caption for the same word is masked. Bleeping the sound while the caption
spells the word out is a common and slightly absurd failure.

The bleep is baked into the clip's audio rather than placed as a separate timeline item. A
separate item can be nudged, muted or deleted by accident; baking it means the censoring
cannot come apart later. The tone itself is generated by gen_sfx.py, so it carries no
licence. Word timings come from Whisper's word-level output, padded either side because a
timestamp lands just inside the word and the tail of a consonant is still recognisable.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "Trade" / "BloopersConformed"
OUT = ROOT / "Trade" / "BloopersCensored"
TRANSCRIPTS = ROOT / "Trade" / "BloopersTranscripts"

# Padding around each word, in seconds. Whisper's boundaries sit slightly inside the word,
# so an unpadded bleep leaves the attack and the tail audible.
PAD_HEAD = 0.10
PAD_TAIL = 0.12

# Matched against the word with punctuation stripped, case-insensitively. Kept as stems with
# explicit suffixes rather than loose substrings: "ass" inside "class" or "pass", and "hell"
# inside "hello", are the classic false positives.
PROFANITY = re.compile(
    r"^(?:"
    r"f+u+c+k+(?:ing|in|ed|er|ers|s)?|"
    r"sh[i1]+t+(?:ty|s|ting)?|"
    r"b[i1]tch(?:es|ing|y)?|"
    r"a+s+h+o+l+e+s?|arsehole s?|"
    r"bastard s?|"
    r"d[i1]ck(?:head|s)?|"
    r"c+u+n+t+s?|"
    r"pr[i1]ck s?|"
    r"wank(?:er|ers|ing)?|"
    r"bollocks|"
    r"bugger(?:ing|ed)?|"
    r"damn(?:it|ed)?|goddamn(?:it)?|"
    r"crap(?:py|s)?|"
    r"bhenchod|behenchod|madarchod|madarchod|chutiya|chutiye|bhosdi(?:ke|wale)?|"
    r"gandu|randi|harami|kamina|kutta|saala|saale"
    r")$",
    re.IGNORECASE,
)


# Bleeps that Whisper cannot find for us. It transcribes nothing at all for the muttered
# word at the end of Prateek's take - the model simply drops audio it cannot resolve, which
# is exactly the audio most likely to need censoring. Located instead by looking at the
# energy envelope: a clear four-burst utterance sitting ~9 dB above room tone, after the
# last word Whisper did transcribe.
#
# (stem, start, end) in seconds. Padding is applied on top, same as a detected word.
MANUAL_BLEEPS: list[tuple[str, float, float]] = [
    ("PXL_20260903_065042375", 24.02, 24.94),
]


def strip_word(w: str) -> str:
    return re.sub(r"[^\w']", "", w).strip("'")


def find_profanity(stem: str) -> list[tuple[float, float, str]]:
    """(start, end, word) for every word that needs bleeping, merged when adjacent."""
    jf = TRANSCRIPTS / f"{stem}.json"
    if not jf.exists():
        return []
    data = json.loads(jf.read_text(encoding="utf-8"))

    hits: list[tuple[float, float, str]] = []
    for seg in data.get("segments", []):
        for w in seg.get("words", []):
            token = strip_word(w.get("word", ""))
            if token and PROFANITY.match(token):
                hits.append((float(w["start"]) - PAD_HEAD,
                             float(w["end"]) + PAD_TAIL,
                             token))

    for st, a, b in MANUAL_BLEEPS:
        if st == stem:
            hits.append((a - PAD_HEAD, b + PAD_TAIL, "manual"))

    # Merge overlapping or near-touching hits so two swear words in a row become one bleep
    # rather than two with an audible gasp between them.
    merged: list[tuple[float, float, str]] = []
    for s, e, t in sorted(hits):
        if merged and s <= merged[-1][1] + 0.08:
            ps, pe, pt = merged[-1]
            merged[-1] = (ps, max(pe, e), f"{pt}+{t}")
        else:
            merged.append((max(0.0, s), e, t))
    return merged


def censor(stem: str, hits: list[tuple[float, float, str]]) -> Path:
    """Mute each span and lay a 1 kHz tone over it, in one pass."""
    src, dst = SRC / f"{stem}.mp4", OUT / f"{stem}.mp4"
    if not hits:
        # Nothing to do - copy through so downstream only ever reads one directory.
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", str(src),
                        "-c", "copy", str(dst)], check=True)
        return dst

    # volume=enable='between(t,a,b)':volume=0 mutes each span; a sine generated for the whole
    # clip is gated to the same spans and mixed back in.
    mutes = "".join(
        f",volume=enable='between(t,{s:.3f},{e:.3f})':volume=0" for s, e, _ in hits
    )
    gate = "+".join(f"between(t,{s:.3f},{e:.3f})" for s, e, _ in hits)

    fc = (
        f"[0:a]aresample=48000{mutes}[clean];"
        f"sine=frequency=1000:sample_rate=48000:duration={_dur(src):.3f},"
        f"volume=-9dB,"
        f"volume=enable='not({gate})':volume=0[tone];"
        f"[clean][tone]amix=inputs=2:normalize=0:duration=first,"
        f"aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo[a]"
    )
    subprocess.run(
        ["ffmpeg", "-y", "-v", "error", "-i", str(src),
         "-filter_complex", fc, "-map", "0:v", "-map", "[a]",
         "-c:v", "copy", "-c:a", "aac", "-b:a", "256k", str(dst)],
        check=True,
    )
    return dst


def _dur(p: Path) -> float:
    return float(subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "csv=p=0", str(p)], capture_output=True, text=True, check=True,
    ).stdout.strip())


def mask(word: str) -> str:
    """What the caption shows instead: first letter, then asterisks."""
    core = word.split("+")[0]
    return core[0] + "*" * max(1, len(core) - 1) if core else "****"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    total = 0
    for src in sorted(SRC.glob("*.mp4")):
        stem = src.stem
        hits = find_profanity(stem)
        censor(stem, hits)
        total += len(hits)
        if hits:
            words = ", ".join(f"{t} @{s:.2f}s" for s, _, t in hits)
            print(f"  {stem:26} {len(hits)} bleep(s): {words}")
        else:
            print(f"  {stem:26} clean")
    print(f"\n{total} bleep(s) total -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
